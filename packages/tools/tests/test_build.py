@pytest.mark.skipif(shutil.which("sh") is None or shutil.which("tar") is None, reason="needs sh")
def test_the_work_copy_drops_every_file_that_names_a_source_or_runs_code(tmp_path: Path) -> None:
    repo = tmp_path / "repo"
    module = repo / "app"
    for name in (
        "app/.npmrc",
        "app/.yarnrc",
        "app/pip.conf",
        "app/uv.toml",
        "app/.pnpmfile.cjs",
        "app/sub/.npmrc",
        "app/.yarn/releases/yarn.cjs",
        "app/.yarn/plugins/p.cjs",
        "app/.git/config",
        "app/node_modules/x/index.js",
        "app/dist/out.js",
        "app/build/out.js",
        "app/src/build/keep.ts",
        "app/package.json",
        "app/.yarn/patches/p.patch",
    ):
        path = repo / name
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text("x\n" if "yarn.lock" not in name else "", encoding="utf-8")
    (module / "yarn.lock").write_text(
        "resolved https://registry.yarnpkg.com/a/-/a-1.tgz\n", encoding="utf-8"
    )
    work = tmp_path / "work"

    done = subprocess.run(
        ["sh", "-c", COPY_SCRIPT, "copy", work.as_posix(), "app", "yarn1"],
        cwd=repo,
        capture_output=True,
        text=True,
        check=False,
    )

    assert done.returncode == 0, done.stderr
    kept = sorted(
        p.relative_to(work / "src").as_posix() for p in (work / "src").rglob("*") if p.is_file()
    )
    assert kept == [".yarn/patches/p.patch", "package.json", "src/build/keep.ts", "yarn.lock"]
    assert "registry.npmjs.org" in (work / "src" / "yarn.lock").read_text(encoding="utf-8")


@pytest.mark.skipif(
    shutil.which("sh") is None or sys.platform == "win32", reason="needs sh and symlinks"
)
def test_the_work_copy_stays_inside_the_repo(tmp_path: Path) -> None:
    (tmp_path / "repo").mkdir()
    (tmp_path / "secret").mkdir()
    (tmp_path / "repo" / "link").symlink_to(tmp_path / "secret")

    done = subprocess.run(
        ["sh", "-c", COPY_SCRIPT, "copy", (tmp_path / "work").as_posix(), "link", "npm"],
        cwd=tmp_path / "repo",
        capture_output=True,
        text=True,
        check=False,
    )

    assert done.returncode == 125


