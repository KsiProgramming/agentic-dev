# What the toolchain in the image can build.


@pytest.mark.parametrize(
    ("manifest", "reason"),
    [
        ({"engines": {"node": ">=18"}}, None),
        ({"engines": {"node": "^20 || ^22"}}, None),
        ({"engines": {"node": "20.x"}}, "needs Node 20"),
        ({"engines": {"node": ">=24"}}, "needs Node 24"),
        ({"engines": {"node": "<20"}}, "needs Node 20"),
        ({"packageManager": "pnpm@9.15.0"}, "needs pnpm 9"),
        ({"packageManager": "pnpm@10.4.1+sha512.abc"}, None),
        ({"packageManager": "yarn@3.6.0"}, "needs yarn 3"),
        ({"packageManager": "npm@11.0.0"}, "needs npm 11"),
    ],
)
def test_a_toolchain_the_image_lacks_is_a_fixed_reason(
    manifest: dict[str, Any], reason: str | None
) -> None:
    manager = manifest.get("packageManager", "")
    lock = {"yarn.lock": YARN_BERRY_LOCK if "yarn@3" in manager else YARN_CLASSIC_LOCK}
    if manager.startswith("pnpm"):
        lock = {"pnpm-lock.yaml": "x"}
    elif manager.startswith("npm") or not lock or "engines" in manifest:
        lock = {"package-lock.json": "{}"}
    files = {"package.json": json.dumps(manifest), **lock}

    [found] = plan(Described(files), ("node",))

    assert found.fail == reason


def test_a_python_the_image_lacks_is_a_fixed_reason() -> None:
    needs = '[project]\nname = "x"\nrequires-python = ">=3.13"\ndependencies = ["six"]\n'
    ok = needs.replace(">=3.13", ">=3.10,<3.13")

    [too_new] = plan(Described({"pyproject.toml": needs}), ("python",))
    [fine] = plan(Described({"pyproject.toml": ok}), ("python",))

    assert (too_new.fail, fine.fail) == ("needs Python 3.13", None)


