class BuildSandbox:
    """Answers the steps of a restore: the module listing, each module's files, the copy and the
    placed files, and the restore and build jobs (scripted results)."""

    workdir = "/workspace/repo"
    staging_dir = STAGING

    def __init__(
        self,
        modules: Mapping[str, Mapping[str, str]],
        *,
        restore: ExecResult | None = None,
        build: ExecResult | None = None,
        copy_exit: int = 0,
        networks: frozenset[JobNetwork] = frozenset({"none", "npm", "pypi"}),
    ) -> None:
        self.modules = modules
        self.restore = restore or ExecResult(0, "::packages:: 42\n", "")
        self.build = build or ExecResult(0, "", "")
        self.copy_exit = copy_exit
        self.job_networks = networks
        self.jobs: list[tuple[JobNetwork, list[str], str, Mapping[str, str]]] = []
        self.placed: dict[str, str] = {}
        self.removed: list[str] = []
        self.staged: dict[str, bytes] = {}

    async def exec(
        self, argv: Sequence[str], *, timeout_s: float = 30.0, cwd: str | None = None
    ) -> ExecResult:
        if argv[0] == "rm":
            self.removed.append(argv[-1])
            return ExecResult(0, "", "")
        step = argv[3]
        if step == "modules":
            listing = "".join(
                "./package.json\n" if m == "." else f"./{m}/package.json\n" for m in self.modules
            )
            return ExecResult(0, f"{listing}::dirs::\n", "")
        if step == "describe":
            module, marker = argv[4], argv[5]
            files = self.modules[module]
            out = "".join(f"{marker} {name}\n{text}\n" for name, text in files.items())
            return ExecResult(0, out, "")
        if step == "copy":
            return ExecResult(self.copy_exit, "", "")
        assert step == "place"
        self.placed[argv[6]] = self.staged.pop(argv[4]).decode()
        return ExecResult(0, "", "")

    async def put_file(self, data: bytes) -> str:
        path = f"{STAGING}/staged-{len(self.staged)}"
        self.staged[path] = data
        return path

    async def run_job(
        self,
        argv: Sequence[str],
        *,
        network: JobNetwork,
        cwd: str,
        timeout_s: float,
        env: Mapping[str, str] | None = None,
    ) -> ExecResult:
        assert cwd.startswith(f"{STAGING}/build-") and cwd.endswith("/src")
        assert network in self.job_networks
        self.jobs.append((network, list(argv), timeout_s.__repr__(), dict(env or {})))
        return self.restore if network != "none" else self.build


async def run(sandbox: BuildSandbox, **kwargs: Any) -> BuildReport:
    return await restore_modules(sandbox, **kwargs)  # type: ignore[arg-type]


def rows(report: BuildReport) -> list[tuple[str, str, str | None, str, str | None]]:
    return [(c.path, c.ecosystem, c.manager, c.status, c.reason) for c in report.checks]


