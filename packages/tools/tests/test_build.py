async def test_the_tool_returns_the_report_as_structured_data() -> None:
    sandbox = BuildSandbox({"app": {"package.json": PACKAGE_JSON, "package-lock.json": "{}"}})
    sandbox.exec_real = sandbox.exec  # type: ignore[attr-defined]

    async def exec_with_confine(
        argv: Sequence[str], *, timeout_s: float = 30.0, cwd: str | None = None
    ) -> ExecResult:
        if argv[3] == "build":  # the path check
            return ExecResult(0, "", "")
        return await sandbox.exec_real(argv, timeout_s=timeout_s, cwd=cwd)  # type: ignore[attr-defined]

    sandbox.exec = exec_with_confine  # type: ignore[method-assign]
    async with Client(build_build_server(sandbox)) as client:  # type: ignore[arg-type]
        result = await client.call_tool("restore", {"path": "app", "ecosystems": ["node"]})

    assert not result.is_error
    report = BuildReport.model_validate(result.structured_content)
    assert [(c.path, c.status) for c in report.checks] == [("app", "ran")]
    assert report.counts["ran"] == 1


async def test_the_tool_refuses_a_path_outside_the_repo() -> None:
    sandbox = BuildSandbox({})
    async with Client(build_build_server(sandbox)) as client:  # type: ignore[arg-type]
        result = await client.call_tool("restore", {"path": "../etc"})

    assert result.is_error
    assert sandbox.jobs == []


